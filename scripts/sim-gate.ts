// Gate simulation matrix: 3 acts × Rites {0,3,6,10} × all 10 parties, via scripts/sim.ts --json.
// usage: bun scripts/sim-gate.ts [--runs 400] [--seed 1] [--rites 0,3,6,10] [--out docs/reports/2026-10-26-sim-gate.md]
// Dry run for the report format: bun scripts/sim-gate.ts --runs 50 --out <scratch path>
import { join } from 'node:path';

const ROOT = join(import.meta.dir, '..');

interface Stat {
	mean: number;
	median: number;
	p90: number;
	n: number;
}
interface SimJson {
	runs: number;
	winRate: number;
	noTankWinRate: number;
	collapseRate: number;
	turnStats: Record<'common' | 'elite' | 'boss', Stat>;
	actReached: number[];
	actCleared: number[];
	heroShare: Record<string, number>;
	rows: { party: string; win: number }[];
}

const args = process.argv.slice(2);
const opt = (k: string, d: string): string => {
	const i = args.indexOf(k);
	return i >= 0 ? (args[i + 1] ?? d) : d;
};
const runs = Number(opt('--runs', '400'));
const seed = Number(opt('--seed', '1'));
const rites = opt('--rites', '0,3,6,10')
	.split(',')
	.map((x) => Number(x.trim()));
const out = opt('--out', join(ROOT, 'docs/reports/2026-10-26-sim-gate.md'));

async function simRite(rite: number): Promise<SimJson> {
	const proc = Bun.spawn(
		[
			'bun',
			join(ROOT, 'scripts/sim.ts'),
			'--runs',
			String(runs),
			'--seed',
			String(seed),
			'--rite',
			String(rite),
			'--acts',
			'3',
			'--json',
		],
		{ stdout: 'pipe', stderr: 'pipe' },
	);
	const text = await new Response(proc.stdout).text();
	const code = await proc.exited;
	if (code !== 0) {
		const err = await new Response(proc.stderr).text();
		throw new Error(`sim.ts failed for Rite ${rite}: ${err.slice(0, 400)}`);
	}
	return JSON.parse(text) as SimJson;
}

const pct = (x: number): string => `${(x * 100).toFixed(1)}`;
const flag = (ok: boolean): string => (ok ? 'pass' : 'FAIL');

// GDD targets: §23.7 (3-act win 18–35%), §20 (no-Shieldbearer >= 25%, collapse >= 40%), §20 hero share >= 15%.
function rowFor(rite: number, s: SimJson): string[] {
	const reached = s.actReached;
	const cleared = s.actCleared;
	const cond = (k: number): string =>
		pct((reached[k] ?? 0) > 0 ? (cleared[k] ?? 0) / (reached[k] ?? 1) : 0);
	const share = Object.values(s.heroShare);
	const minShare = share.length ? Math.min(...share) : 0;
	const win = s.winRate;
	return [
		String(rite),
		pct(win),
		flag(win >= 0.18 && win <= 0.35),
		pct((cleared[0] ?? 0) / s.runs),
		pct((cleared[1] ?? 0) / s.runs),
		pct((cleared[2] ?? 0) / s.runs),
		`${cond(0)} / ${cond(1)} / ${cond(2)}`,
		pct(s.noTankWinRate),
		flag(s.noTankWinRate >= 0.25),
		pct(s.collapseRate),
		flag(s.collapseRate >= 0.4),
		`${s.turnStats.common.median} / ${s.turnStats.common.p90}`,
		`${s.turnStats.elite.median} / ${s.turnStats.elite.p90}`,
		`${s.turnStats.boss.median} / ${s.turnStats.boss.p90}`,
		`${pct(minShare)} ${flag(minShare >= 0.15)}`,
	];
}

const results: { rite: number; s: SimJson }[] = [];
for (const rite of rites) {
	const t0 = performance.now();
	const s = await simRite(rite);
	results.push({ rite, s });
	console.log(
		`Rite ${rite}: win ${pct(s.winRate)}% (${((performance.now() - t0) / 1000).toFixed(1)} s)`,
	);
}

const heroes = Object.keys(results[0]?.s.heroShare ?? {});
const parties = (results[0]?.s.rows ?? []).map((r) => r.party);
const lines: string[] = [];
lines.push('# Gate simulation matrix');
lines.push('');
lines.push(
	`Generated by \`bun scripts/sim-gate.ts --runs ${runs} --seed ${seed} --rites ${rites.join(',')}\` on ${new Date().toISOString()}. Three acts (\`--acts 3\`), greedy bot, all 10 party compositions, ${runs} runs per composition (${runs * 10} per Rite).`,
);
lines.push('');
lines.push(
	'Targets: 3-act win 18–35% (GDD §23.7); no-Shieldbearer win ≥ 25% and collapse runs ≥ 40% (GDD §20); every hero ≥ 15% of wins (GDD §20). Clear % columns are shares of all runs; the conditional column is clears over runs that entered the act (Act 1 / Act 2 / Act 3).',
);
lines.push('');
lines.push('## Summary per Rite');
lines.push('');
lines.push(
	'| Rite | Win % | Target | Act 1 clear % | Act 2 clear % | Act 3 clear % | Conditional clear % (A1 / A2 / A3) | No-Shieldbearer win % | Target | Collapse % | Target | Common turns median / p90 | Elite turns median / p90 | Boss turns median / p90 | Lowest hero share of wins |',
);
lines.push(
	'| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
);
for (const { rite, s } of results) lines.push(`| ${rowFor(rite, s).join(' | ')} |`);
lines.push('');
lines.push('## Hero share of winning parties');
lines.push('');
lines.push(`| Hero | ${results.map((r) => `Rite ${r.rite}`).join(' | ')} |`);
lines.push(`| --- | ${results.map(() => '---').join(' | ')} |`);
for (const h of heroes) {
	lines.push(`| ${h} | ${results.map((r) => `${pct(r.s.heroShare[h] ?? 0)}%`).join(' | ')} |`);
}
lines.push('');
lines.push('## Win rate per party composition');
lines.push('');
lines.push(`| Party | ${results.map((r) => `Rite ${r.rite}`).join(' | ')} |`);
lines.push(`| --- | ${results.map(() => '---').join(' | ')} |`);
for (const p of parties) {
	const cells = results.map((r) => {
		const row = r.s.rows.find((x) => x.party === p);
		return row ? `${pct(row.win)}%` : '-';
	});
	lines.push(`| ${p} | ${cells.join(' | ')} |`);
}
lines.push('');
lines.push(
	'Raw numbers come from `scripts/sim.ts --json`. Re-run the command above after any balance change; do not edit this file by hand.',
);
lines.push('');

await Bun.write(out, lines.join('\n'));
console.log(`wrote ${out}`);
